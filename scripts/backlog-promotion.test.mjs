const DEFAULT_ENTRY = {
  Title: 'Add short poll links',
  Type: 'Quality',
  Level: 'Low',
  State: '—',
  Notes: 'Short IDs for poll URLs; needs a redirect',
  'Dependencies / context': 'ID-2',
};

function maxBacklogId(backlog) {
  return Math.max(
    0,
    ...[...backlog.todo.rows, ...backlog.done.rows].map((row) => Number(row.cells[0])),
  );
}

function nextBacklogId(backlog, reservedIds = []) {
  return nextIds(backlog, reservedIds, 1)[0];
}

// A recommendation in the issue-triage comment format; a field set to
// `undefined` is left out.
function triageBody({ verdict = 'Keep', entries = [{}] } = {}) {
  const sections = entries.map((entry) =>
    [
      '### Candidate backlog entry',
      '',
      ...Object.entries({ ...DEFAULT_ENTRY, ...entry })
        .filter(([, value]) => value !== undefined)
        .map(([name, value]) => `- **${name}:** ${value}`),
      '',
    ].join('\n'),
  );
  return [
    '## Triage recommendation',
    '',
    `**Verdict:** ${verdict}`,
    '**Proposed backlog title:** Add short poll links',
    '',
    '### Dependencies / context',
    '',
    '- ID-2',
    '',
    ...(verdict === 'Keep' ? sections : []),
    '_Recommendation only — nothing was changed._',
    '',
    MARKERS,
  ].join('\n');
}

function triageComment(body = triageBody(), overrides = {}) {
  return {
    id: 5906921993,
    user: { login: 'github-actions[bot]', type: 'Bot' },
    body,
    html_url: `https://github.com/${REPOSITORY}/issues/62#issuecomment-5906921993`,
    created_at: '2026-09-30T08:05:47Z',
    updated_at: '2026-09-30T08:05:47Z',
    ...overrides,
  };
}

const httpError = (status, message = `HTTP ${status}`) =>
  Object.assign(new Error(message), { status });

// An in-memory GitHub REST API that records every request.
function fakeGitHub({
  permission = 'admin',
  issue = {},
  comments = [triageComment()],
  promotionPulls = [],
  openPulls = [],
  pullFiles = {},
  branches = [],
  failures = {},
  backlog = realBacklog,
} = {}) {
  const state = { branches: new Set(branches), comments: [], calls: [] };
  const branchOf = (route) => route.split('/heads/')[1];
  const routes = [
    ['GET /repos/{owner}/{repo}/collaborators/{username}/permission', () => ({ permission })],
    [
      'GET /repos/{owner}/{repo}/issues/{issue_number}',
      () => ({ number: 62, state: 'open', labels: [{ name: ACCEPTED_LABEL }], ...issue }),
    ],
    [
      'GET /repos/{owner}/{repo}/pulls',
      (params) => (params.state === 'all' ? promotionPulls : openPulls),
    ],
    ['GET /repos/{owner}/{repo}/issues/{issue_number}/comments', () => comments],
    [
      'GET /repos/{owner}/{repo}/pulls/{pull_number}/files',
      (params) => pullFiles[params.pull_number] ?? [],
    ],
    ['GET /repos/{owner}/{repo}/git/ref/heads/main', () => ({ object: { sha: BASE_SHA } })],
    [
      (route) => route.startsWith('GET /repos/{owner}/{repo}/git/ref/heads/'),
      (params, route) => {
        if (state.branches.has(branchOf(route))) return { object: { sha: BASE_SHA } };
        throw httpError(404);
      },
    ],
    [
      `GET /repos/{owner}/{repo}/contents/${BACKLOG_PATH}`,
      () => ({
        sha: BLOB_SHA,
        encoding: 'base64',
        content: Buffer.from(backlog).toString('base64'),
      }),
    ],
    [
      'POST /repos/{owner}/{repo}/git/refs',
      (params) => {
        const branch = params.ref.replace('refs/heads/', '');
        if (state.branches.has(branch)) throw httpError(422, 'Reference already exists');
        state.branches.add(branch);
        return {};
      },
    ],
    [
      `PUT /repos/{owner}/{repo}/contents/${BACKLOG_PATH}`,
      () => ({ commit: { sha: 'c'.repeat(40) } }),
    ],
    [
      'POST /repos/{owner}/{repo}/pulls',
      () => ({ number: 70, html_url: `https://github.com/${REPOSITORY}/pull/70` }),
    ],
    [
      (route) => route.startsWith('DELETE /repos/{owner}/{repo}/git/refs/heads/'),
      (params, route) => {
        state.branches.delete(branchOf(route));
        return {};
      },
    ],
    [
      'POST /repos/{owner}/{repo}/issues/{issue_number}/comments',
      (params) => {
        state.comments.push(params.body);
        return {};
      },
    ],
  ];
  async function request(route, params = {}) {
    state.calls.push({ route, params });
    if (failures[route]) throw failures[route];
    const match = routes.find(([key]) => (typeof key === 'string' ? key === route : key(route)));
    if (!match) throw new Error(`unexpected request: ${route}`);
    return { data: await match[1](params, route) };
  }
  return {
    request,
    paginate: async (route, params) => (await request(route, params)).data,
    state,
    writes: () =>
      state.calls
        .filter(({ route }) => !route.startsWith('GET '))
        .filter(({ route }) => !route.endsWith('/comments'))
        .map(({ route }) => route.split(' ')[0] + ' ' + route.split('{repo}')[1]),
  };
}

function fakeCore() {
  const core = { failed: null, notices: [], warnings: [], summaryText: '' };
  core.setFailed = (message) => (core.failed = message);
  core.notice = (message) => core.notices.push(message);
  core.warning = (message) => core.warnings.push(message);
  core.info = () => {};
  core.summary = {
    addRaw(text) {
      core.summaryText += text;
      return this;
    },
    async write() {},
  };
  return core;
}

function fakeContext(overrides = {}) {
  return {
    repo: { owner: 'avshukan', repo: 'rank-vote' },
    serverUrl: 'https://github.com',
    runId: 99,
    eventName: 'issues',
    payload: {
      sender: { login: 'avshukan' },
      repository: { default_branch: 'main' },
      issue: { number: 62 },
    },
    ...overrides,
  };
}

async function promote62(github, options = {}) {
  const core = fakeCore();
  const result = await promote({
    github,
    context: fakeContext(),
    core,
    issueNumber: 62,
    ...options,
  });
  return { result, core, comment: github.state.comments.join('\n') };
}

