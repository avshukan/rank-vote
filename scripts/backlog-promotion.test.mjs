test('a recommendation is parsed as written, including a split', () => {
  const parsed = parseTriage(triageBody({ entries: [{}, { Title: 'Second item', Notes: 'Two' }] }));

  assert.deepEqual(parsed.verdicts, ['Keep']);
  assert.equal(parsed.entries.length, 2);
  assert.equal(parsed.entries[1].Title, 'Second item');
  assert.equal(parsed.entries[0]['Dependencies / context'], 'ID-2');
  assert.deepEqual(parsed.duplicates, []);
});

test('a valid entry passes unchanged and starts with State —', () => {
  const backlog = parseBacklog(realBacklog);
  const { entries, problems } = validateEntries(parseTriage(triageBody()), backlog);

  assert.deepEqual(problems, []);
  assert.deepEqual(entries, [
    {
      Title: 'Add short poll links',
      Type: 'Quality',
      Level: 'Low',
      State: '—',
      Notes: 'Short IDs for poll URLs; needs a redirect',
      dependencies: 'ID-2',
    },
  ]);
});

test('overlong values are reported with their length and limit, never shortened', () => {
  const backlog = parseBacklog(realBacklog);
  const { problems } = validateEntries(parseTriage(ISSUE_62_TRIAGE), backlog);

  assert.deepEqual(problems, [
    'The candidate entry: Notes is 54 characters; the `Todo` Notes column fits 51: ' +
      '`Replace/alias UUID with short ID; needs redirect layer`',
  ]);
});

test('entries that would break the table or the process are refused', () => {
  const backlog = parseBacklog(realBacklog);
  const entries = [
    { Title: 'A | B' },
    { Title: 'Add 🎉 support' },
    { Title: 'Fixes #3 quickly' },
    { Type: 'Feature' },
    { Level: 'Urgent' },
    { State: 'Ready' },
    { Notes: undefined },
    { Notes: '…' },
  ];
  const problems = validateEntries(parseTriage(triageBody({ entries })), backlog).problems.join(
    '\n',
  );

  assert.match(problems, /1 of 8: Title contains `\|`/);
  assert.match(problems, /2 of 8: Title contains a character that is not one column wide/);
  assert.match(problems, /3 of 8: Title contains an issue-closing reference/);
  assert.match(
    problems,
    /4 of 8: Type `Feature` is not a Legend value \(Value, Quality, Refactor, Ops\)/,
  );
  assert.match(problems, /5 of 8: Level `Urgent` is not a Legend value/);
  assert.match(problems, /6 of 8: State is `Ready`; a new backlog item starts with `—`/);
  assert.match(problems, /7 of 8 has no `- \*\*Notes:\*\*` line/);
  assert.match(problems, /8 of 8: Notes is empty/);
});

